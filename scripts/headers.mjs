// Writes dist/_headers after `astro build`: security headers for every page, with a Content
// Security Policy whose script-src lists the sha256 of each inline <script> Starlight emits
// (theme, sidebar and search glue), so no 'unsafe-inline' is needed for scripts. They are
// hashed from the built files, so the policy always matches the build.
//
// Styles need 'unsafe-inline': Expressive Code colours code tokens with style="" attributes.
// Pagefind (search) runs WebAssembly, hence 'wasm-unsafe-eval'.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;

async function* htmlFiles(dir) {
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) yield* htmlFiles(path);
		else if (entry.name.endsWith('.html')) yield path;
	}
}

const hashes = new Set();
let pages = 0;
for await (const file of htmlFiles(dist)) {
	pages++;
	const html = await readFile(file, 'utf8');
	for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
		if (/\bsrc\s*=/.test(attrs) || /type\s*=\s*["']?application\/(ld\+)?json/.test(attrs)) continue;
		hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
	}
}

const csp = [
	"default-src 'self'",
	`script-src 'self' 'wasm-unsafe-eval' ${[...hashes].sort().join(' ')}`,
	"style-src 'self' 'unsafe-inline'",
	"img-src 'self' data:",
	"font-src 'self'",
	"connect-src 'self'",
	"object-src 'none'",
	"base-uri 'self'",
	"form-action 'self'",
	"frame-ancestors 'none'",
	'upgrade-insecure-requests',
].join('; ');

await writeFile(
	join(dist, '_headers'),
	`# Generated by scripts/headers.mjs at build time; edit that file, not this one.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=604800
`,
);

console.log(`_headers: ${hashes.size} inline script hash(es) from ${pages} page(s)`);
